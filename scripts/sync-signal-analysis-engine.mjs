import { readFile, writeFile } from 'node:fs/promises';

const sourcePath = new URL('../src/services/technicalAnalysis.js', import.meta.url);
const targetPath = new URL('../supabase/functions/signal-notifications/technicalAnalysis.shared.js', import.meta.url);

const source = await readFile(sourcePath, 'utf8');
const edgeCompatible = source.replace(
  "import { supabase } from '../lib/supabase';",
  "const supabase = null; // Generated Edge copy: network helpers below are not called by signal-notifications.",
);

if (edgeCompatible === source) throw new Error('找不到 technicalAnalysis 的 Supabase import，請更新同步腳本。');

await writeFile(
  targetPath,
  `// Generated by npm run sync:signal-engine. Do not edit this file directly.\n${edgeCompatible}`,
  'utf8',
);
