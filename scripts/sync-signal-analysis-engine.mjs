import { readFile, writeFile } from 'node:fs/promises';

const sourcePath = new URL('../src/services/technicalAnalysis.js', import.meta.url);
const targetPath = new URL('../supabase/functions/signal-notifications/technicalAnalysis.shared.js', import.meta.url);
const strategyEngineSourcePath = new URL('../src/services/strategyEngines.js', import.meta.url);
const strategyEngineTargetPath = new URL('../supabase/functions/signal-notifications/strategyEngines.js', import.meta.url);
const strategyLibrarySourcePath = new URL('../src/services/strategyLibrary.js', import.meta.url);
const strategyLibraryTargetPath = new URL('../supabase/functions/signal-notifications/strategyLibrary.js', import.meta.url);

const source = await readFile(sourcePath, 'utf8');
const edgeCompatible = source
  .replace(
    "import { Platform } from 'react-native';",
    "const Platform = { OS: 'edge' }; // Generated Edge copy: use direct provider fallbacks.",
  )
  .replace(
    "import { supabase } from '../lib/supabase';",
    "const supabase = null; // Generated Edge copy: network helpers below are not called by signal-notifications.",
  );

if (edgeCompatible === source) throw new Error('找不到 technicalAnalysis 的 Supabase import，請更新同步腳本。');
if (edgeCompatible.includes("from 'react-native'") || edgeCompatible.includes("from '../lib/supabase'")) {
  throw new Error('technicalAnalysis 的 Edge 同步產物仍含有 React Native 或 Supabase app import。');
}

await writeFile(
  targetPath,
  `// Generated by npm run sync:signal-engine. Do not edit this file directly.\n${edgeCompatible}`,
  'utf8',
);

await Promise.all([
  readFile(strategyEngineSourcePath, 'utf8').then(source => writeFile(strategyEngineTargetPath, `// Generated by npm run sync:signal-engine. Do not edit this file directly.\n${source}`, 'utf8')),
  readFile(strategyLibrarySourcePath, 'utf8').then(source => writeFile(strategyLibraryTargetPath, `// Generated by npm run sync:signal-engine. Do not edit this file directly.\n${source}`, 'utf8')),
]);
